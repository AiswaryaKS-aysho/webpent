import json
from datetime import datetime, timezone

from .core.models import ScanResult, Severity

_SEV_ICON = {
    Severity.CRITICAL: "🔴 CRITICAL",
    Severity.HIGH: "🟠 HIGH",
    Severity.MEDIUM: "🟡 MEDIUM",
    Severity.LOW: "🔵 LOW",
    Severity.INFO: "⚪ INFO",
}


def write_json(result: ScanResult, path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        json.dump(result.to_dict(), fh, indent=2, ensure_ascii=False)


def render_markdown(result: ScanResult) -> str:
    counts = result.counts()
    lines = [
        "# webpent scan report",
        "",
        f"- **Target:** `{result.target}`",
        f"- **Started:** {result.started_at}",
        f"- **Finished:** {result.finished_at}",
        f"- **Probes:** {', '.join(result.probes_run) or 'none'}",
        "",
        "## Summary",
        "",
        "| Severity | Count |",
        "|---|---|",
    ]
    for sev in Severity:
        lines.append(f"| {sev.value} | {counts[sev.value]} |")
    lines.append("")

    findings = result.sorted_findings()
    if not findings:
        lines += ["_No findings._", ""]
    else:
        lines.append("## Findings")
        lines.append("")
        for i, f in enumerate(findings, 1):
            lines += [
                f"### {i}. [{_SEV_ICON[f.severity]}] {f.title}",
                "",
                f"- **Probe:** {f.probe}",
                f"- **URL:** `{f.url}`",
            ]
            if f.param:
                lines.append(f"- **Parameter:** `{f.param}`")
            if f.payload:
                lines.append(f"- **Payload:** `{f.payload}`")
            lines.append(f"- **Confidence:** {f.confidence}")
            if f.evidence:
                lines.append(f"- **Evidence:** {f.evidence}")
            if f.remediation:
                lines.append(f"- **Remediation:** {f.remediation}")
            lines.append("")

    if result.errors:
        lines += ["## Errors", ""]
        lines += [f"- {e}" for e in result.errors]
        lines.append("")

    lines += [
        "---",
        "",
        f"_Generated by webpent at {datetime.now(timezone.utc).isoformat(timespec='seconds')}_",
        "",
    ]
    return "\n".join(lines)


def write_markdown(result: ScanResult, path: str) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write(render_markdown(result))


def print_summary(result: ScanResult) -> None:
    counts = result.counts()
    print()
    print("=" * 60)
    print(f"  Scan complete: {result.target}")
    print("=" * 60)
    for sev in reversed(list(Severity)):
        n = counts[sev.value]
        if n:
            print(f"  {_SEV_ICON[sev]}: {n}")
    if not result.findings:
        print("  No findings.")
    print("=" * 60)
